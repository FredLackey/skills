// wt-signing.mjs
//
// Author identity and SSH signing are configured once per workstation, not in
// each repository. From the workspace configuration this module generates:
//
//   {config dir}/git/{account}.gitconfig  name, email, key, and signing rules
//   {config dir}/git/routes.gitconfig     one includeIf per routed owner
//
// and registers routes.gitconfig in the user's global Git configuration.
// Conditional includes match the primary clone's directory, so every linked
// worktree of that clone inherits the same identity.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DEFAULT_HOST, gitIncludeDir, identityFor, loadConfig } from './wt-config.mjs';
import { git, gitOrNull, REPOS_ROOT } from './wt-lib.mjs';

export const SIGNING_KEYS = ['user.name', 'user.email', 'user.signingkey', 'gpg.format', 'commit.gpgsign', 'tag.gpgsign'];

function expandHome(value) {
  if (value === '~') return os.homedir();
  if (value.startsWith('~/')) return path.join(os.homedir(), value.slice(2));
  return value;
}

function quote(value) {
  if (/["\\\n]/.test(value)) throw new Error(`Unsupported character in Git configuration value: ${value}`);
  return `"${value}"`;
}

/** Expected effective Git settings for an identity. */
export function expectedSettings(identity) {
  return {
    'user.name': identity.gitUserName,
    'user.email': identity.gitUserEmail,
    'user.signingkey': expandHome(identity.sshKeyPath),
    'gpg.format': 'ssh',
    'commit.gpgsign': 'true',
    'tag.gpgsign': 'true',
  };
}

export function routesIncludePath() {
  return path.join(gitIncludeDir(), 'routes.gitconfig');
}

/** Generated files, as { path: content }. */
export function renderWorkstationFiles() {
  const config = loadConfig();
  const dir = gitIncludeDir();
  const files = {};
  const header = '# Generated by wt-enforce-signing.mjs from the workspace configuration. Do not edit.\n';
  for (const accountId of Object.keys(config.accounts)) {
    const settings = expectedSettings(identityFor(accountId));
    files[path.join(dir, `${accountId}.gitconfig`)] = header +
      `[user]\n\tname = ${quote(settings['user.name'])}\n\temail = ${quote(settings['user.email'])}\n` +
      `\tsigningkey = ${quote(settings['user.signingkey'])}\n` +
      '[gpg]\n\tformat = ssh\n[commit]\n\tgpgsign = true\n[tag]\n\tgpgsign = true\n';
  }
  const lines = [header];
  for (const [host, table] of Object.entries(config.routes)) {
    for (const [owner, accountId] of Object.entries(table).sort(([a], [b]) => a.localeCompare(b))) {
      const ownerDir = host === DEFAULT_HOST ? path.join(REPOS_ROOT, owner) : path.join(REPOS_ROOT, host, owner);
      lines.push(`[includeIf ${quote(`gitdir/i:${ownerDir}/`)}]\n\tpath = ${quote(path.join(dir, `${accountId}.gitconfig`))}\n`);
    }
  }
  files[routesIncludePath()] = lines.join('');
  return files;
}

function globalIncludes() {
  return (gitOrNull(['config', '--global', '--get-all', 'include.path']) ?? '')
    .split('\n').filter(Boolean).map(entry => path.resolve(expandHome(entry)));
}

/** Differences between generated files and disk, plus global registration. */
export function workstationStatus() {
  const files = Object.entries(renderWorkstationFiles()).map(([file, content]) => {
    let current = null;
    try { current = fs.readFileSync(file, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    return { file, content, state: current === null ? 'create' : current === content ? 'keep' : 'replace' };
  });
  const registered = globalIncludes().includes(routesIncludePath());
  return { files, registered, ready: registered && files.every(entry => entry.state === 'keep') };
}

/** Writes generated files; registers the global include only when `register` is true. */
export function writeWorkstationFiles({ register = false } = {}) {
  const status = workstationStatus();
  fs.mkdirSync(gitIncludeDir(), { recursive: true, mode: 0o700 });
  for (const entry of status.files) {
    if (entry.state === 'keep') continue;
    fs.writeFileSync(entry.file, entry.content, { mode: 0o600 });
    fs.chmodSync(entry.file, 0o600);
  }
  if (register && !status.registered) git(['config', '--global', '--add', 'include.path', routesIncludePath()]);
  return status;
}

/** Throws unless the workstation signing configuration is installed and current. */
export function assertWorkstationReady() {
  if (!workstationStatus().ready) {
    throw new Error('Workstation signing configuration is missing or out of date. Run wt-enforce-signing.mjs, then retry.');
  }
}

/**
 * Effective identity/signing values in a repository, compared with the routed
 * identity. Returns drift entries: { key, expected, actual, origin, local }.
 */
export function effectiveDrift(repoDir, identity) {
  const expected = expectedSettings(identity);
  const output = gitOrNull(['config', '--show-origin', '--get-regexp',
    '^(user\\.(name|email|signingkey)|gpg\\.format|commit\\.gpgsign|tag\\.gpgsign)$'], { cwd: repoDir }) ?? '';
  const actual = {};
  for (const line of output.split('\n').filter(Boolean)) {
    const match = line.match(/^([^\t]+)\t(\S+) ?(.*)$/);
    if (!match) continue;
    const [, origin, key, value] = match;
    actual[key.toLowerCase()] = { value, origin };
  }
  return SIGNING_KEYS.flatMap(key => {
    const found = actual[key];
    const normalize = value => key === 'user.signingkey' ? path.resolve(expandHome(value)) : value;
    if (found && normalize(found.value) === normalize(expected[key])) return [];
    return [{ key, expected: expected[key], actual: found?.value ?? null, origin: found?.origin ?? null,
      local: Boolean(found?.origin && /^file:(\.git\/config|.*\/\.git\/config)$/.test(found.origin)) }];
  });
}

/** Keys set in a repository's own configuration (these override the workstation). */
export function localOverrides(repoDir) {
  return SIGNING_KEYS.filter(key => gitOrNull(['config', '--local', '--get-all', key], { cwd: repoDir }) !== null);
}

/** Removes identity/signing keys from a repository's own configuration. */
export function removeLocalOverrides(repoDir) {
  const removed = localOverrides(repoDir);
  for (const key of removed) git(['config', '--local', '--unset-all', key], { cwd: repoDir });
  return removed;
}

export function describeDrift(drift) {
  return drift.map(entry => `${entry.key}=${entry.actual ?? '(unset)'}${entry.origin ? ` from ${entry.origin}` : ''}`).join(', ');
}
